package revisao.numeros.ex02operacoes;

public class SqrtPow {
    public static void main(String[] args) {

        double x = 16;

        //raiz quadrada
        double y = Math.sqrt(x);
        System.out.println(y);

        //potência
        double z = 8;
        double k = Math.pow(z, 3);
        System.out.println(k);
    }
}
